def render_report(captures: Iterable[Capture], title: str = "API behaviour") -> str:
    captures = list(captures)
    analysis = analyse(captures)
    notes = gaps(captures, analysis)

    out: List[str] = []
    out.append("# %s" % title)
    out.append("")
    out.append(
        "Generated by [apirecorder](https://github.com/varun1414/api-recorder) from "
        "recorded traffic. Everything under **Observed** appeared in the recordings. "
        "Everything under **Not observed** did not, and says nothing about how the "
        "API behaves in general - only about what these recordings cover."
    )
    out.append("")
    out.append(
        "- Captures: %s" % (", ".join("`%s`" % n for n in analysis.capture_names) or "none")
    )
    out.append("- Interactions: %d" % analysis.interaction_count)
    out.append("- Operations: %d" % len(analysis.operations))
    out.append("- Distinct endpoints: %d" % analysis.endpoint_count)
    if analysis.failed_count:
        out.append("- Transport failures: %d" % analysis.failed_count)
    out.append("")

    # -- observed
    out.append("## Observed")
    out.append("")
    out.append("### Operations")
    out.append("")
    rows = []
    for op in analysis.sorted_operations():
        status_cell = ", ".join(
            "%d x%d" % (g.status, g.count)
            for g in sorted(op.statuses.values(), key=lambda g: g.status)
        )
        rows.append(
            [
                op.method,
                "`%s`" % op.template,
                str(op.count),
                status_cell or "-",
                _ms(op.p50_ms),
                _ms(op.max_ms),
            ]
        )
    out.append(
        _md_table(
            ["method", "endpoint", "calls", "statuses seen", "p50 ms", "max ms"], rows
        )
    )
    out.append("")

    # -- per-operation response shape
    for op in analysis.sorted_operations():
        shown = [g for g in op.statuses.values() if g.fields]
        if not shown:
            continue
        out.append("### %s" % op.label)
        out.append("")
        if op.examples:
            out.append("Example: `%s`" % op.examples[0])
            out.append("")
        for group in sorted(shown, key=lambda g: g.status):
            out.append(
                "**%d** - %d response(s), %d with a structured body"
                % (group.status, group.count, group.bodies_analysed)
            )
            out.append("")
            field_rows = []
            for stat in group.fields.values():
                presence = (
                    "always"
                    if stat.always_present
                    else "%d of %d" % (stat.present, stat.total)
                )
                field_rows.append(
                    ["`%s`" % stat.path, stat.type_label, presence]
                )
            out.append(_md_table(["field", "type", "present"], field_rows))
            out.append("")

        stable = op.stable_headers()
        if stable:
            out.append("Stable response headers:")
            out.append("")
            out.append(
                _md_table(
                    ["header", "value"],
                    [["`%s`" % k, "`%s`" % v] for k, v in sorted(stable.items())],
                )
            )
            out.append("")

    # -- sequence
    out.append("### Call sequence")
    out.append("")
    for name in analysis.capture_names:
        steps = [
            "%s %s -> %s" % (method, template, status if status is not None else "ERR")
            for cap_name, method, template, status in analysis.sequence
            if cap_name == name
        ]
        out.append("`%s`:" % name)
        out.append("")
        for index, step in enumerate(steps, 1):
            out.append("%d. %s" % (index, step))
        out.append("")

    # -- not observed
    out.append("## Not observed")
    out.append("")
    if notes:
        out.append(
            "These are gaps in the recording. Each one is a path your code may "
            "have that no recorded traffic exercised."
        )
        out.append("")
        for note in notes:
            out.append("- %s" % note)
    else:
        out.append("_Nothing flagged._")
    out.append("")

    return "\n".join(out)


