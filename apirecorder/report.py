_HEADINGS = (
    (BREAKING, "BREAKING"),
    (ADDITIVE, "ADDITIVE"),
    (INFO, "INFO"),
)


def render_diff(diff: Diff, show_info: bool = True) -> str:
    counts = []
    if diff.breaking:
        counts.append("%d breaking" % len(diff.breaking))
    if diff.additive:
        counts.append("%d additive" % len(diff.additive))
    if diff.info:
        counts.append("%d info" % len(diff.info))

    if not diff.has_changes:
        return "No changes against baseline (%s -> %s)." % (
            diff.baseline_label,
            diff.current_label,
        )

    out: List[str] = []
    out.append(
        "%d change(s) against baseline (%s)"
        % (len(diff.changes), ", ".join(counts))
    )
    out.append("%s -> %s" % (diff.baseline_label, diff.current_label))
    out.append("")

    for severity, heading in _HEADINGS:
        group = diff.of(severity)
        if not group or (severity == INFO and not show_info):
            continue
        by_scope: List[str] = []
        current_scope = None
        for change in sorted(group, key=lambda c: (c.operation, c.status or "", c.category)):
            if change.scope != current_scope:
                current_scope = change.scope
                by_scope.append("%-9s %s" % (heading, current_scope))
            by_scope.append("          %s" % change.detail)
        out.extend(by_scope)
        out.append("")

    return "\n".join(out).rstrip() + "\n"


def render_diff_markdown(diff: Diff) -> str:
    out = ["# API drift", ""]
    if not diff.has_changes:
        out.append(
            "No changes between `%s` and `%s`." % (diff.baseline_label, diff.current_label)
        )
        out.append("")
        return "\n".join(out)

    out.append("`%s` -> `%s`" % (diff.baseline_label, diff.current_label))
    out.append("")
    for severity, heading in _HEADINGS:
        group = diff.of(severity)
        if not group:
            continue
        out.append("## %s (%d)" % (heading.title(), len(group)))
        out.append("")
        out.append(
            _md_table(
                ["scope", "category", "change"],
                [
                    ["`%s`" % c.scope, c.category, c.detail]
                    for c in sorted(group, key=lambda c: (c.operation, c.status or ""))
                ],
            )
        )
        out.append("")
    return "\n".join(out)
