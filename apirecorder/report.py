def render_inspect(captures: Iterable[Capture]) -> str:
    """One block per capture: the calls, in the order they happened."""
    from .analyze import template_path

    blocks: List[str] = []
    for capture in captures:
        total_ms = sum(i.duration_ms or 0 for i in capture.interactions)
        header = "%s - %d interaction(s), %.1fs total" % (
            capture.name,
            len(capture.interactions),
            total_ms / 1000.0,
        )
        if capture.recorded_at:
            header += "  [recorded %s]" % capture.recorded_at

        rows = []
        for interaction in capture.interactions:
            if interaction.response is None:
                status = "ERR"
                note = interaction.error or "no response"
            else:
                status = str(interaction.response.status)
                body = interaction.response.body
                kind = body.get("kind") if isinstance(body, dict) else None
                note = "" if kind in STRUCTURED_KINDS else (kind or "")
            rows.append(
                [
                    str(interaction.seq),
                    interaction.request.method,
                    template_path(interaction.request.path),
                    status,
                    _ms(interaction.duration_ms),
                    note,
                ]
            )

        blocks.append(
            header
            + "\n\n"
            + _table(["#", "method", "endpoint", "status", "ms", "note"], rows)
        )

    if not blocks:
        return "No recordings found."
    return "\n\n".join(blocks)


