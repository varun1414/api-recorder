"""Rendering: the inspect table, the behaviour report, and the diff output."""

from __future__ import annotations

from typing import Iterable, List, Optional, Sequence

from .analyze import Analysis, analyse, gaps
from .diff import ADDITIVE, BREAKING, INFO, Diff
from .model import STRUCTURED_KINDS, Capture


def _table(headers: Sequence[str], rows: Sequence[Sequence[str]], gap: str = "  ") -> str:
    """A plain fixed-width table for terminal output."""
    if not rows:
        return ""
    widths = [len(h) for h in headers]
    for row in rows:
        for index, cell in enumerate(row):
            widths[index] = max(widths[index], len(cell))

    def line(cells: Sequence[str]) -> str:
        return gap.join(cell.ljust(widths[i]) for i, cell in enumerate(cells)).rstrip()

    out = [line(headers), line(["-" * w for w in widths])]
    out.extend(line(row) for row in rows)
    return "\n".join(out)


def _md_table(headers: Sequence[str], rows: Sequence[Sequence[str]]) -> str:
    if not rows:
        return "_none_"
    out = ["| " + " | ".join(headers) + " |"]
    out.append("|" + "|".join(["---"] * len(headers)) + "|")
    for row in rows:
        out.append("| " + " | ".join(row) + " |")
    return "\n".join(out)


def _ms(value: Optional[int]) -> str:
    return "-" if value is None else str(value)


